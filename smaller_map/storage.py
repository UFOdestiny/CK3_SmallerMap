"""Generated-path confinement, output modes, manifest and rebuild report."""

from __future__ import annotations

import hashlib
import json
from pathlib import Path
import re
from PIL import Image

from .common import UpdateError, log
from .installation import supported_version

MANIFEST_NAME = ".smaller_map_generated.json"
REPORT_NAME = ".smaller_map_report.json"


def managed_existing(repo: Path) -> set[Path]:
    manifest_path = repo / MANIFEST_NAME
    if not manifest_path.is_file():
        return set()
    data = json.loads(manifest_path.read_text(encoding="utf-8"))
    return {Path(item) for item in data.get("generated_files", [])}


def mod_target(mod: Path, relative: Path) -> Path:
    if relative.is_absolute():
        raise UpdateError(f"Generated path must be relative: {relative}")
    root = mod.resolve()
    target = (root / relative).resolve()
    try:
        target.relative_to(root)
    except ValueError as error:
        raise UpdateError(f"Generated path escapes the mod directory: {relative}") from error
    return target


def updated_descriptor(game: Path, mod: Path) -> str:
    version = supported_version(game)
    descriptor = mod / "descriptor.mod"
    source = descriptor.read_text(encoding="utf-8-sig")
    updated, count = re.subn(
        r'^supported_version="[^\r\n]*"(\r?)$',
        lambda line: f'supported_version="{version}"{line.group(1)}',
        source,
        flags=re.MULTILINE,
    )
    if count != 1:
        raise UpdateError(f"Expected exactly one supported_version in {descriptor}, found {count}")
    return updated


def encoded_text(relative: Path, source: str) -> bytes:
    encoding = "utf-8" if relative == Path("descriptor.mod") else "utf-8-sig"
    return source.encode(encoding)


def verify_outputs(repo: Path, mod: Path, text_outputs: dict[Path, str],
                   province_image: Image.Image) -> None:
    """One verifier shared by read-only checks and post-write validation."""
    expected = set(text_outputs) | {Path("map_data/provinces.png")}
    managed = managed_existing(repo)
    drift = []
    for relative, source in sorted(text_outputs.items()):
        path = mod_target(mod, relative)
        if not path.is_file() or path.read_bytes() != encoded_text(relative, source):
            drift.append(relative.as_posix())
    map_path = mod_target(mod, Path("map_data/provinces.png"))
    if not map_path.is_file():
        drift.append("map_data/provinces.png (missing)")
    else:
        with Image.open(map_path) as image:
            if (image.mode != "RGB" or image.size != province_image.size
                    or image.tobytes() != province_image.tobytes()):
                drift.append("map_data/provinces.png (pixel mismatch)")
    if managed != expected:
        drift.append(MANIFEST_NAME + " (file set mismatch)")
    drift.extend(path.as_posix() + " (stale)" for path in managed - expected
                 if mod_target(mod, path).exists())
    if drift:
        raise UpdateError("Generated output is out of date:\n" + "\n".join(drift[:30]))


def write_outputs(
    repo: Path,
    mod: Path,
    text_outputs: dict[Path, str],
    province_image: Image.Image,
    dry_run: bool,
    check: bool = False,
    report: dict | None = None,
) -> tuple[int, int]:
    outputs = set(text_outputs) | {Path("map_data/provinces.png")}
    stale = managed_existing(repo) - outputs
    # Resolve every managed path before any deletion/write, including old manifests.
    targets = {relative: mod_target(mod, relative) for relative in outputs | stale}
    if check:
        verify_outputs(repo, mod, text_outputs, province_image)
        log(f"CHECK: {len(outputs)} generated files match current game/configuration, including every map pixel")
        return len(outputs), 0
    if dry_run:
        log(f"DRY RUN: would write {len(outputs)} files and delete {len(stale)} stale generated files")
        return len(outputs), len(stale)
    for relative in sorted(stale):
        if targets[relative].is_file():
            targets[relative].unlink()
    for relative, source in sorted(text_outputs.items()):
        path = targets[relative]
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_bytes(encoded_text(relative, source))
    map_path = targets[Path("map_data/provinces.png")]
    map_path.parent.mkdir(parents=True, exist_ok=True)
    temp = map_path.with_suffix(".png.tmp")
    province_image.save(temp, format="PNG", compress_level=6)
    temp.replace(map_path)
    manifest = {
        "generated_files": sorted(path.as_posix() for path in outputs),
        "note": "Generated by update_mod.py; files not listed here are not managed by the generator.",
    }
    (repo / MANIFEST_NAME).write_text(json.dumps(manifest, indent=2) + "\n", encoding="utf-8")
    verify_outputs(repo, mod, text_outputs, province_image)
    if report is not None:
        saved_report = {
            **report,
            "generated_sha256": {
                relative.as_posix(): hashlib.sha256(targets[relative].read_bytes()).hexdigest()
                for relative in sorted(outputs)
            },
        }
        (repo / REPORT_NAME).write_text(
            json.dumps(saved_report, ensure_ascii=False, indent=2) + "\n", encoding="utf-8",
        )
    return len(outputs), len(stale)
